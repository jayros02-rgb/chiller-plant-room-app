# ---------------------------------------------------------------------------
# --- Green Mark Dashboard logic ---
# ---------------------------------------------------------------------------
def greenmark_check(chiller_kw_per_rt, pump_kw_per_rt, approach_c, cycles):
    results = {}
    results["Chiller Efficiency"] = "Pass" if chiller_kw_per_rt <= 0.65 else "Fail"
    results["Pump Efficiency"] = "Pass" if pump_kw_per_rt <= 0.04 else "Fail"
    results["Cooling Tower Approach"] = "Pass" if approach_c <= 3.5 else "Fail"
    results["Cycles of Concentration"] = "Pass" if cycles >= 5 else "Fail"
    return results


def weighted_scoring(results):
    weights = {
        "Chiller Efficiency": 40,
        "Pump Efficiency": 20,
        "Cooling Tower Approach": 20,
        "Cycles of Concentration": 20,
    }
    scores = {}
    for k, v in results.items():
        scores[k] = weights[k] if v == "Pass" else 0
    total = sum(scores.values())
    return scores, total


def assign_greenmark_rating(total_score):
    if total_score >= 95:
        return "Super Low Energy (SLE)"
    elif total_score >= 90:
        return "Platinum"
    elif total_score >= 75:
        return "GoldPLUS"
    elif total_score >= 60:
        return "Gold"
    else:
        return "Certified"


# ---------------------------------------------------------------------------
# --- PDF Export ---
# ---------------------------------------------------------------------------
def generate_pdf_report(results, scores, total_score, rating,
                         company_name="Jayros Technologies Inc.", logo_path="logo.png"):
    pdf = FPDF()
    pdf.add_page()

    # Logo (optional, silently skipped if missing)
    if logo_path and os.path.exists(logo_path):
        try:
            pdf.image(logo_path, x=10, y=8, w=30)
        except Exception:
            pass

    # Header
    pdf.set_font("Arial", "B", 16)
    pdf.cell(200, 10, f"{company_name}", ln=True, align="C")
    pdf.set_font("Arial", "I", 12)
    pdf.cell(200, 10, "Singapore Green Mark Compliance Report", ln=True, align="C")
    pdf.ln(20)

    # Table Header
    pdf.set_font("Arial", "B", 12)
    pdf.cell(100, 10, "Parameter", 1)
    pdf.cell(40, 10, "Status", 1)
    pdf.cell(50, 10, "Score", 1)
    pdf.ln()

    # Table Content
    pdf.set_font("Arial", "", 12)
    for k, v in results.items():
        pdf.cell(100, 10, k, 1)
        pdf.cell(40, 10, v, 1)
        pdf.cell(50, 10, str(scores[k]), 1)
        pdf.ln()

    # Total + Rating
    pdf.ln(10)
    pdf.set_font("Arial", "B", 14)
    pdf.cell(200, 10, f"Total Score: {total_score}/100", ln=True, align="C")
    pdf.cell(200, 10, f"Overall Green Mark Rating: {rating}", ln=True, align="C")

    # Footer
    pdf.set_y(-30)
    pdf.set_font("Arial", "I", 10)
    pdf.cell(200, 10, "Generated by Jayros Technologies Compliance Tool", ln=True, align="C")

    return pdf.output(dest="S").encode("latin-1")


# ---------------------------------------------------------------------------
# --- Supplier datasheet comparison helpers ---
# ---------------------------------------------------------------------------
def load_supplier_file(uploaded_file):
    """Read a single uploaded CSV/Excel file into a DataFrame, tagged with source filename."""
    name = uploaded_file.name
    try:
        if name.lower().endswith(".csv"):
            df = pd.read_csv(uploaded_file)
        else:
            df = pd.read_excel(uploaded_file)
        df["__source_file"] = name
        return df, None
    except Exception as e:
        return None, str(e)


def build_comparison_table(dataframes):
    """Stack supplier dataframes on shared columns for side-by-side comparison."""
    if not dataframes:
        return pd.DataFrame()
    common_cols = set(dataframes[0].columns)
    for df in dataframes[1:]:
        common_cols &= set(df.columns)
    common_cols.discard("__source_file")
    ordered_cols = ["__source_file"] + sorted(common_cols)
    combined = pd.concat([df[ordered_cols] for df in dataframes], ignore_index=True)
    combined = combined.rename(columns={"__source_file": "Source File"})
    return combined


