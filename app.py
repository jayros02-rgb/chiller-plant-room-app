st.title("Chiller Plant Room Verification Tool (Singapore Green Mark)")

tab1, tab2, tab3, tab4, tab5, tab6, tab7, tab8, tab9 = st.tabs([
    "Chiller", "Piping", "Pump", "Cooling Tower", "Make-up Water",
    "Expansion Tank", "Green Mark Dashboard", "Export Report", "Supplier Data"
])

with tab1:
    st.header("Chiller Verification")
    cop = st.number_input("Chiller COP", value=5.5, min_value=0.01, step=0.1)
    kw_per_ton = 3.516 / cop
    st.write(f"Chiller Efficiency: {kw_per_ton:.2f} kW/RT")
    st.session_state["kw_per_ton"] = kw_per_ton

with tab2:
    st.header("Piping Verification")
    flow_lps = st.number_input("Flow (L/s)", value=15.0, min_value=0.0, step=0.5)
    pipe_d_mm = st.number_input("Pipe Diameter (mm)", value=150.0, min_value=1.0, step=5.0)
    vel_ms = flow_lps / (math.pi * (pipe_d_mm / 1000 / 2) ** 2) if pipe_d_mm > 0 else 0
    st.write(f"Pipe Velocity: {vel_ms:.2f} m/s")
    st.session_state["flow_lps"] = flow_lps

with tab3:
    st.header("Pump Verification")
    required_head = st.number_input("Required Head (m)", value=12.0)
    required_flow = st.number_input("Required Flow (L/s)", value=15.0)
    pump_head = st.number_input("Supplier Pump Head (m)", value=15.0)
    pump_flow = st.number_input("Supplier Pump Flow (L/s)", value=16.0)
    st.write("✅ Pump meets requirements" if pump_head >= required_head and pump_flow >= required_flow
              else "❌ Pump undersized")

with tab4:
    st.header("Cooling Tower Verification")
    t_hot = st.number_input("Hot Water Temp (°C)", value=35.0)
    t_cold = st.number_input("Cold Water Temp (°C)", value=29.0)
    t_wb = st.number_input("Wet Bulb Temp (°C)", value=26.0)
    approach_val = t_cold - t_wb
    st.write(f"Approach: {approach_val:.1f} °C")
    st.session_state["approach_val"] = approach_val

with tab5:
    st.header("Make-up Water & Tank")
    flow_for_makeup = st.session_state.get("flow_lps", flow_lps)
    total = flow_for_makeup * (0.0015 + 0.001 + 0.015)
    tank_volume = total * 3600 * 24 * 1.5
    st.write(f"Make-up Water Flow: {total:.3f} L/s")
    st.write(f"Tank Volume: {tank_volume:.1f} L")

with tab6:
    st.header("Expansion Tank / Degassing")
    system_volume = st.number_input("System Volume (m³)", value=50.0)
    delta_t_c = st.number_input("Temperature Rise (°C)", value=10.0)
    expansion_vol = system_volume * delta_t_c * 0.00021
    tank_size = expansion_vol * 1.25
    st.write(f"Expansion Volume: {expansion_vol:.2f} m³")
    st.write(f"Expansion Tank Size: {tank_size:.2f} m³")

with tab7:
    st.header("Singapore Green Mark Dashboard")
    cycles = st.number_input("Cycles of Concentration", value=5, min_value=1, step=1)

    kw_per_ton = st.session_state.get("kw_per_ton", kw_per_ton)
    approach_val = st.session_state.get("approach_val", approach_val)

    gm_results = greenmark_check(kw_per_ton, 0.03, approach_val, cycles)
    scores, total_score = weighted_scoring(gm_results)
    rating = assign_greenmark_rating(total_score)

    for k, v in gm_results.items():
        color = "green" if v == "Pass" else "red"
        st.markdown(f"**{k}:** <span style='color:{color}'>{v}</span> — Score: {scores[k]}",
                    unsafe_allow_html=True)

    st.markdown(f"### Total Score: **{total_score}/100**")
    st.markdown(f"### Overall Rating: **{rating}**")

    # Gauge visualization
    fig = go.Figure(go.Indicator(
        mode="gauge+number",
        value=total_score,
        title={"text": "Green Mark Score"},
        gauge={
            "axis": {"range": [0, 100]},
            "bar": {"color": "darkblue"},
            "steps": [
                {"range": [0, 60], "color": "red"},
                {"range": [60, 75], "color": "orange"},
                {"range": [75, 90], "color": "yellow"},
                {"range": [90, 95], "color": "green"},
                {"range": [95, 100], "color": "purple"},  # Super Low Energy
            ],
        },
    ))
    st.plotly_chart(fig, use_container_width=True)

    # Persist for the Export tab
    st.session_state["gm_results"] = gm_results
    st.session_state["scores"] = scores
    st.session_state["total_score"] = total_score
    st.session_state["rating"] = rating

with tab8:
    st.header("Export Compliance Report")

    if "gm_results" not in st.session_state:
        st.warning("Please visit the **Green Mark Dashboard** tab first to generate results.")
    else:
        company_name = st.text_input("Company Name", value="Jayros Technologies Inc.")
